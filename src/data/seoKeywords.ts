// Global cached mapping of all unique keyword pages
let cachedAllPages: SeoPageMetaData[] | null = null;

export function getAllSeoPages(): SeoPageMetaData[] {
  if (cachedAllPages) return cachedAllPages;

  const seenSlugs = new Set<string>();
  const pages: SeoPageMetaData[] = [];

  RAW_KEYWORD_LIST.forEach((raw) => {
    const page = generateSeoPageData(raw);
    if (!seenSlugs.has(page.slug) && page.cleanKeyword.length > 1) {
      seenSlugs.add(page.slug);
      pages.push(page);
    }
  });

  cachedAllPages = pages;
  return pages;
}

export function getSeoPageBySlug(slug: string): SeoPageMetaData | undefined {
  const pages = getAllSeoPages();
  const found = pages.find((p) => p.slug === slug || slugify(p.cleanKeyword) === slug);
  if (found) return found;

  // Fallback match: check if raw keyword matches
  const fallbackRaw = RAW_KEYWORD_LIST.find((r) => slugify(r) === slug);
  if (fallbackRaw) {
    return generateSeoPageData(fallbackRaw);
  }
  return undefined;
}

export function getCategories(): { id: string; label: string; count: number }[] {
  const pages = getAllSeoPages();
  const counts: Record<string, { label: string; count: number }> = {};

  pages.forEach((p) => {
    if (!counts[p.category]) {
      counts[p.category] = { label: p.categoryLabel, count: 0 };
    }
    counts[p.category].count += 1;
  });

  return Object.entries(counts).map(([id, val]) => ({
    id,
    label: val.label,
    count: val.count,
  }));
}
