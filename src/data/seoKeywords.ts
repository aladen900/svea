function categorizeKeyword(kw: string): SeoPageMetaData['category'] {
  const k = kw.toLowerCase();
  if (k.includes('olagligt') || k.includes('laglig') || k.includes('lagar') || k.includes('dömd') || k.includes('åtal') || k.includes('vpn') || k.includes('säkerhet') || k.includes('spåra')) {
    return 'Legality';
  }
  if (k.includes('leverantör') || k.includes('bästa iptv') || k.includes('flashback') || k.includes('omdöme') || k.includes('reddit') || k.includes('jämför') || k.includes('nordic') || k.includes('viking') || k.includes('pongo') || k.includes('king') || k.includes('köpa') || k.includes('beställa') || k.includes('paket') || k.includes('pris') || k.includes('billig')) {
    return 'Providers';
  }
  if (k.includes('app') || k.includes('smarters') || k.includes('gse') || k.includes('vlc') || k.includes('kodi') || k.includes('ibo') || k.includes('spela') || k.includes('spelare') || k.includes('tivimate')) {
    return 'Apps';
  }
  if (k.includes('box') || k.includes('formuler') || k.includes('mag') || k.includes('router') || k.includes('fjärrkontroll') || k.includes('tv') || k.includes('apple tv') || k.includes('firestick') || k.includes('samsung') || k.includes('lg') || k.includes('hardware') || k.includes('utrustning') || k.includes('switch') || k.includes('modem')) {
    return 'Hardware';
  }
  if (k.includes('kanal') || k.includes('sport') || k.includes('fotboll') || k.includes('film') || k.includes('vod') || k.includes('arabisk') || k.includes('turkisk') || k.includes('alban') || k.includes('m3u') || k.includes('epg') || k.includes('allsvenskan')) {
    return 'Channels';
  }
  if (k.includes('fungerar inte') || k.includes('funkar inte') || k.includes('laggar') || k.includes('hackar') || k.includes('störningar') || k.includes('felsökning') || k.includes('uppdatera') || k.includes('startar inte') || k.includes('slutit') || k.includes('buffrar')) {
    return 'Troubleshooting';
  }
  return 'Guides';
}

function getCategoryLabel(cat: SeoPageMetaData['category']): string {
  switch (cat) {
    case 'Legality': return '⚖️ Laglighet & Regler 2026';
    case 'Providers': return '⭐ Bästa Leverantörer & Recensioner';
    case 'Apps': return '📱 IPTV Appar & Spelare';
    case 'Hardware': return '📺 Boxar, Routers & TV-Inställningar';
    case 'Channels': return '⚽ Kanallistor, Sport & VOD';
    case 'Troubleshooting': return '🔧 Felsökning & Stabil Drift';
    case 'Guides': return '📖 Steg-för-steg Guider';
  }
}

